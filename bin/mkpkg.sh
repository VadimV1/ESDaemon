#!/bin/bash
# mkpkg.sh — build the macOS installer package build/ESDaemon-<version>.pkg. Run on macOS: pkgbuild is macOS-only.
#
# The .pkg is a thin delivery wrapper around install.sh, for MDM (Jamf / Kandji / Intune), which deploys .pkg files
# rather than `curl … | sudo bash`. It does NOT reimplement the install: the payload stages the install sources
# under /Library/ESDaemon/pkg-staging (an opaque dir, NOT the final tree), and a postinstall script runs install.sh
# from there and then removes the staging dir. Because install.sh does the work, a .pkg install is identical to a
# script install — it keeps a tuned config, ad-hoc signs + verifies the binary and checks its architecture, and
# loads both LaunchDaemons — and `esdaemon reload` / `esdaemon uninstall` behave the same afterwards.
#
# It needs a prebuilt build/ESDaemon (the writer binary) to bundle; if it is missing it builds one with `make build`.
# The release workflow places the universal (arm64 + x86_64) binary at build/ESDaemon before calling this, so the
# released .pkg carries the universal binary and the target Mac needs no Swift toolchain.
#
# Signing (optional, off by default). Set ESDAEMON_PKG_SIGN_ID to a "Developer ID Installer: …" identity to sign:
#   ESDAEMON_PKG_SIGN_ID="Developer ID Installer: Example, Inc. (TEAMID)" ./bin/mkpkg.sh
# Unsigned is fine for MDM, which is the trust anchor on managed devices. Developer ID Installer signing (here) plus
# notarization is the planned path for manual / non-MDM installs; see SECURITY.md. (To sign an existing unsigned
# package instead, `productsign --sign "$ESDAEMON_PKG_SIGN_ID" in.pkg out.pkg`.)
set -euo pipefail
# fixed PATH is not forced here: unlike the install scripts this is a build tool, run by a developer / CI as a
# normal user, and `make build` may reach the Swift toolchain through the caller's PATH. The postinstall it
# generates, which DOES run as root during the install, pins PATH like install.sh.

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IDENTIFIER=com.esdaemon.pkg          # the package receipt id; uninstall.sh and bin/esdaemon pkgutil --forget it
STAGING_ABS=/Library/ESDaemon/pkg-staging    # where the payload lands; the postinstall runs install.sh from here
VER="$(tr -d ' \r\n' < "$ROOT/VERSION")"
OUT="$ROOT/build/ESDaemon-$VER.pkg"

command -v pkgbuild >/dev/null || { echo "mkpkg.sh: pkgbuild not found — build the .pkg on macOS (CI / lab), not here" >&2; exit 1; }

# The writer binary to bundle. The release workflow drops the universal binary at build/ESDaemon first; otherwise
# build one here so a plain `make pkg` on a lab Mac works. install.sh on the target uses this prebuilt binary (it
# tests `-x build/ESDaemon`), so the Mac needs no swiftc.
if [ ! -x "$ROOT/build/ESDaemon" ]; then
  echo "mkpkg.sh: build/ESDaemon missing — building it with 'make build'"
  make -C "$ROOT" build || { echo "mkpkg.sh: could not build build/ESDaemon (needs Xcode Command Line Tools). Build it with 'make build', or place a prebuilt universal binary at build/ESDaemon, then re-run." >&2; exit 1; }
fi
[ -x "$ROOT/build/ESDaemon" ] || { echo "mkpkg.sh: build/ESDaemon is still missing after the build; cannot package" >&2; exit 1; }

# Stage the install sources (everything install.sh needs) into a payload tree that mirrors the target filesystem:
# with --install-location / the payload root maps to /, so $PAYLOAD/Library/ESDaemon/pkg-staging -> $STAGING_ABS.
PAYLOAD="$(mktemp -d)"; SCRIPTS="$(mktemp -d)"
trap 'rm -rf "$PAYLOAD" "$SCRIPTS"' EXIT
STAGE="$PAYLOAD$STAGING_ABS"
mkdir -p "$STAGE/build"
cp "$ROOT/install.sh" "$ROOT/uninstall.sh" "$ROOT/VERSION" "$ROOT/REPO" "$STAGE/"
cp -R "$ROOT/bin" "$ROOT/src" "$ROOT/configs" "$STAGE/"
cp "$ROOT/build/ESDaemon" "$STAGE/build/ESDaemon"
# install.sh tests `-x build/ESDaemon`, so the bundled binary must be executable (a bit-stripped checkout can
# arrive without the bit); pkgbuild records file modes into the package. The scripts are bash-invoked and
# re-installed with their modes by install.sh, so only the binary strictly needs it; set install.sh/uninstall.sh
# too for a tidy payload.
chmod 755 "$STAGE/build/ESDaemon" "$STAGE/install.sh" "$STAGE/uninstall.sh"

# The postinstall: runs as root during the install. Pin PATH like the other root scripts, run install.sh from the
# staging dir, then remove staging. Generated here so the staging path has a single definition in this file.
cat > "$SCRIPTS/postinstall" <<POSTINSTALL
#!/bin/bash
# postinstall — generated by bin/mkpkg.sh. Runs as root during the ESDaemon .pkg install.
# The payload staged the install sources at $STAGING_ABS; run install.sh from there — the same install as the
# script path (it keeps a tuned config, verifies the binary + architecture, and reload loads both LaunchDaemons).
# install.sh lays the real tree at /usr/local/ESDaemon itself; this only removes the staging dir afterwards.
set -euo pipefail
export PATH=/usr/bin:/bin:/usr/sbin:/sbin
bash "$STAGING_ABS/install.sh"
rm -rf "$STAGING_ABS"
rmdir "${STAGING_ABS%/*}" 2>/dev/null || true
exit 0
POSTINSTALL
chmod 755 "$SCRIPTS/postinstall"

# Build the component package. --root + --install-location / lay the staged payload at $STAGING_ABS; --scripts
# bundles the postinstall. Append --sign only when an identity is set (kept out of "$@" otherwise so an empty
# argument is never passed, which also keeps this bash-3.2-safe under set -u).
mkdir -p "$ROOT/build"
set -- --identifier "$IDENTIFIER" --version "$VER" --install-location / --root "$PAYLOAD" --scripts "$SCRIPTS"
[ -z "${ESDAEMON_PKG_SIGN_ID:-}" ] || set -- "$@" --sign "$ESDAEMON_PKG_SIGN_ID"
pkgbuild "$@" "$OUT"

echo "mkpkg.sh: built $OUT"
if [ -n "${ESDAEMON_PKG_SIGN_ID:-}" ]; then
  echo "mkpkg.sh: signed with $ESDAEMON_PKG_SIGN_ID"
else
  echo "mkpkg.sh: unsigned (set ESDAEMON_PKG_SIGN_ID to a 'Developer ID Installer: …' identity to sign; see SECURITY.md)"
fi
